    private void botaoSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoSalvarActionPerformed
        if(!cbOficial.isSelected()){
            if(veiculo == null){
                veiculo = new Veiculo();
            }
            veiculo.setPlaca(textoPlaca.getText());
            veiculo.setCor(textoCor.getText());
            veiculo.setModelo((Modelo)cmbModelo.getSelectedItem());
            veiculo.setProprietario((Pessoa)cmbProprietario.getSelectedItem());
            veiculo.setTipo((TipoVeiculo)cmbTipoVeiculo.getSelectedItem());
            
            jpa.conexaoAberta();
            try {
                jpa.persist(veiculo);
            } catch (Exception ex) {
                java.util.logging.Logger.getLogger(TelaCadastroPessoa.class.getName()).log(Level.SEVERE, null, ex);
            }
            jpa.fecharConexao();
        }else{
            if(oficial == null){
                oficial = new VeiculoOficial();
            }
            oficial.setPlaca(textoPlaca.getText());
            oficial.setCor(textoCor.getText());
            oficial.setModelo((Modelo)cmbModelo.getSelectedItem());
            oficial.setTipo((TipoVeiculo)cmbTipoVeiculo.getSelectedItem());
            oficial.setChassi(textoChassi.getText());
            oficial.setRenavan(textoRenavan.getText());
            
            jpa.conexaoAberta();
            try {
                jpa.persist(oficial);
            } catch (Exception ex) {
                java.util.logging.Logger.getLogger(TelaCadastroPessoa.class.getName()).log(Level.SEVERE, null, ex);
            }
            jpa.fecharConexao();
        }
        dispose();
    }//GEN-LAST:event_botaoSalvarActionPerformed

