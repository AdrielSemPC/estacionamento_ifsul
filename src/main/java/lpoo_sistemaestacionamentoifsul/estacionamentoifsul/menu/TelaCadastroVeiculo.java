    private void carregarCmbTipo() {
        cmbTipoVeiculo.removeAllItems();
        for(TipoVeiculo t : TipoVeiculo.values()){
            cmbTipoVeiculo.addItem(t);
        }
    }
    
    private void carregarCmbProprietario() {
        cmbProprietario.removeAllItems();
        
        listaP = new ArrayList<>();
        
        jpa.conexaoAberta();
        
        listaP.addAll(jpa.getPessoas());
        
        jpa.fecharConexao();
        
        for(Pessoa p : listaP){
            cmbProprietario.addItem(p);
        }
    }

    private void carregarCmbModelo() {
        cmbModelo.removeAllItems();
        jpa.conexaoAberta();
        
        listaM = new ArrayList<>();
        
        listaM.addAll(jpa.getModelos());
        listaM.toString();
        
        jpa.fecharConexao();
        
        for(Modelo m : listaM){
            cmbModelo.addItem(m);
        }
    }
    
    public void verificaOficial(){
        if(cbOficial.isSelected()){
            cmbProprietario.setEnabled(false);
            textoRenavan.setEnabled(true);
            textoChassi.setEnabled(true);
        }else{
            cmbProprietario.setEnabled(true);
            textoRenavan.setEnabled(false);
            textoChassi.setEnabled(false);
        }
    }
