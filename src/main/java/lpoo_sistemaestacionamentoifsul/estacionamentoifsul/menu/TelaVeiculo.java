    private void botaoEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoEditarActionPerformed
        Veiculo v = listaVeiculos.getSelectedValue();
        if(v!=null){
            try{
                TelaCadastroVeiculo telaCadastro = new TelaCadastroVeiculo(this,rootPaneCheckingEnabled);
                telaCadastro.setVeiculo(v);
                telaCadastro.setVisible(true);
                carregarVeiculosCadastrados();
            }catch(Exception e){
                JOptionPane.showMessageDialog(this, "Erro ao editar pessoa "+v+".\n" + e);
            }
        }
    }//GEN-LAST:event_botaoEditarActionPerformed

    private void botaoRemoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoRemoverActionPerformed
        Veiculo v = listaVeiculos.getSelectedValue();
        if(v!=null){
            try{
                jpa.conexaoAberta();
                
                int del = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja remover "+v.getPlaca()+"?");
                
                if(del == JOptionPane.YES_OPTION){
                    jpa.remover(v);
                }
                
                carregarVeiculosCadastrados();
                jpa.fecharConexao();
                
            }catch (Exception e){
                JOptionPane.showMessageDialog(this, "Erro ao remover veículo "+v.getPlaca()+".\n" + e);
            }
        }
    }//GEN-LAST:event_botaoRemoverActionPerformed

    private void cbOficialActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbOficialActionPerformed
        if(cbOficial.isSelected()){
            carregarVeiculosOficiais();
        }else{
            carregarVeiculosCadastrados();
        }
    }//GEN-LAST:event_cbOficialActionPerformed

