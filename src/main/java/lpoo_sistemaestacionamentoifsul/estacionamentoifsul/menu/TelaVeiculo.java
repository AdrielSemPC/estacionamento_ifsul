    private void carregarVeiculosCadastrados() {
        jpa.conexaoAberta();
        
        DefaultListModel modeloLista = new DefaultListModel();
        modeloLista.addAll(jpa.getVeiculos());
        listaVeiculos.setModel(modeloLista);
        
        listaVeiculos.toString();
        
        jpa.fecharConexao();
    }

    private void carregarVeiculosOficiais() {
        jpa.conexaoAberta();
        
        DefaultListModel modeloLista = new DefaultListModel();
        modeloLista.addAll(jpa.getVeiculosOficial());
        listaVeiculos.setModel(modeloLista);
        
        listaVeiculos.toString();
        
        jpa.fecharConexao();
    }

    private void carregarVeiculosPlaca(String placa) {
        jpa.conexaoAberta();
        
        DefaultListModel modeloLista = new DefaultListModel();
        modeloLista.addAll(jpa.getVeiculosPlaca(placa));
        listaVeiculos.setModel(modeloLista);
        
        listaVeiculos.toString();
        
        jpa.fecharConexao();
    }
